  'computer',
  'content_copy',
  'dark_mode',
  'dashboard',
  'database',
  'delete',
  'description',
  'device_thermostat',
  'dns',
  'download',
  'error',
  'keyboard_arrow_down',
  'filter_list',
  'folder',
  'group',
  'history',
  'how_to_reg',
  'hub',
  'info',
  'key',
  'lan',
  'light_mode',
  'list',
  'lock',
  'logout',
  'memory',
  'menu',
