// Extracts the Material Symbols (Apache-2.0) outlined icons the UI uses into a TypeScript map of
// SVG path data, so icons render as inline <svg> elements without an icon font or innerHTML.
// Usage: npm run icons (after adding a name to ICONS below).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

